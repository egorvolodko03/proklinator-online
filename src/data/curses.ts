export function getRandomCurse(severity?: string): Curse {
  const pool = severity 
    ? CURSES.filter((c) => c.severity === severity)
    : CURSES;
  const list = pool.length > 0 ? pool : CURSES;
  return list[Math.floor(Math.random() * list.length)];
}
